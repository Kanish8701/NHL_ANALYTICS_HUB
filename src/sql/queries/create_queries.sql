-- create the database

create database nhl_analytics_hub;

-- use the database

use nhl_analytics_hub;

-- create the tables (7)

create table teams(
team_id int PRIMARY KEY AUTO_INCREMENT,
team_abbrev VARCHAR(10) UNIQUE,
team_name VARCHAR(100),
conference_name VARCHAR(50),
division_name VARCHAR(50),
logo_url TEXT
);

CREATE TABLE STANDINGS(
STANDING_ID INT PRIMARY KEY AUTO_INCREMENT,
TEAM_ID INT,
  SEASON VARCHAR(20),
  GAMES_PLAYED INT,
  WINS INT,
  LOSSES INT,
  OT_LOSSES INT,
  POINTS INT,
  GOALS_FOR INT,
  GOALS_AGAINST INT,
  FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
  );

CREATE TABLE PLAYERS(
PLAYER_ID BIGINT PRIMARY KEY,
TEAM_ID INT,
  FIRST_NAME VARCHAR(100),
  LAST_NAME VARCHAR(100),
  POSITION VARCHAR(100),
  JERSEY_NUMBER INT,
  BIRTH_DATE DATE,
  BIRTH_COUNTRY VARCHAR(10),
  HEIGHT_CM REAL,
  WEIGHT_KG REAL,
  SHOOTS_CATCHES VARCHAR(5),
  HEADSHOT_URL TEXT,
  FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
);

CREATE TABLE GAMES(
  GAME_ID BIGINT PRIMARY KEY,
  SEASON VARCHAR(20),
  GAME_TYPE INT,
  GAME_DATE DATE,
  HOME_TEAM_ID INT,
  AWAY_TEAM_ID INT,
  HOME_SCORE INT,
  AWAY_SCORE INT,
  GAME_STATE VARCHAR(20),
  VENUE_NAME VARCHAR(150),
  FOREIGN KEY (HOME_TEAM_ID) REFERENCES TEAMS(TEAM_ID),
  FOREIGN KEY (AWAY_TEAM_ID) REFERENCES TEAMS(TEAM_ID)
  );

CREATE TABLE GAME_STATS(
  STAT_ID INT PRIMARY KEY AUTO_INCREMENT,
  GAME_ID BIGINT,
  PLAYER_ID BIGINT,
  TEAM_ID INT,
  GOALS INT,
  ASSISTS INT,
  POINTS INT,
  SHOTS_ON_GOAL INT,
  PENALTY_MIN INT,
  TOI VARCHAR(10),
  PLUS_MINUS INT,
  FOREIGN KEY (PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID),
  FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
);

CREATE TABLE SKATER_SEASON_STATS(
  STAT_ID INT PRIMARY KEY AUTO_INCREMENT,
  PLAYER_ID BIGINT,
  SEASON VARCHAR(20),
  TEAM_ID INT,
  GAMES_PLAYED INT,
  GOALS INT,
  ASSISTS INT,
  POINTS INT,
  PLUS_MINUS INT,
  PENALTY_MIN INT,
  SHOTS INT,
  AVG_TOI VARCHAR(10),
  FOREIGN KEY (PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID),
  FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
  );
 
CREATE TABLE GOALIE_SEASON_STATS(
  STAT_ID INT PRIMARY KEY AUTO_INCREMENT, 
  PLAYER_ID BIGINT,
  SEASON VARCHAR(20),
  TEAM_ID INT,
  GAMES_PLAYED INT,
  WINS INT,
  LOSSES INT,
  OT_LOSSES INT,
  SAVE_PCT FLOAT,
  GOALS_AGAINST_AVG FLOAT,
  SHUTOUTS INT,
  SAVES INT,
  FOREIGN KEY (PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID),
  FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
);
 

